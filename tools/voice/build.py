"""Word-align the voice-over and generate the HyperFrames root: cues.js, captions, index.html
(scene hosts, voice, music bed with ducking lane, SFX clips)."""
import json, os, re, sys, difflib, warnings, html
warnings.filterwarnings("ignore")
HERE = os.path.dirname(os.path.abspath(__file__))
PROJ = "/home/user/work/keyman"
VO = json.load(open(f"{HERE}/vo_lines.json"))

SCENES = [("hook", ["hook1", "hook2", "hook3"]), ("staf", ["s1a", "s1b"]), ("bills", ["s2a", "s2b"]),
          ("loan", ["s3a", "s3b", "s3c"]), ("keyman", ["sol1", "sol2"]), ("cta", ["cta"])]
LEAD = 0.3      # a scene opens this long before its first word
TAIL = 1.9      # hold after the last word


def norm(w):
    return re.sub(r"[^a-z0-9]", "", w.lower())


def align():
    cache = f"{HERE}/align.json"
    if os.path.exists(cache):
        c = json.load(open(cache))
        old = {l["id"]: l for l in c["lines"]}
        if all(l["id"] in old and old[l["id"]]["take"] == l["take"] for l in VO["lines"]):
            out = []
            for l in VO["lines"]:   # same takes, new placement: shift the cached word times
                d = l["start"] - old[l["id"]]["start"]
                out.append({**old[l["id"]], **l, "words": [{**w, "s": round(w["s"] + d, 3), "e": round(w["e"] + d, 3)} for w in old[l["id"]]["words"]]})
            return out
    import torch, librosa
    from transformers import pipeline
    torch.set_num_threads(4)
    pipe = pipeline("automatic-speech-recognition", model="openai/whisper-large-v3-turbo", device="cpu")
    y, _ = librosa.load(f"{PROJ}/assets/audio/vo.wav", sr=16000)
    out = []
    for L in VO["lines"]:
        a, b = int((L["start"] - 0.05) * 16000), int((L["end"] + 0.05) * 16000)
        r = pipe(y[a:b], return_timestamps="word", generate_kwargs={"language": "malay", "task": "transcribe"})
        ww = [(c["text"].strip(), c["timestamp"][0], c["timestamp"][1] or c["timestamp"][0] + 0.3) for c in r["chunks"]]
        off = L["start"] - 0.05
        sw = L["text"].split()
        sm = difflib.SequenceMatcher(None, [norm(w) for w in sw], [norm(w[0]) for w in ww], autojunk=False)
        times = [None] * len(sw)
        for tag, i1, i2, j1, j2 in sm.get_opcodes():
            if tag == "equal" or (tag == "replace" and i2 - i1 == j2 - j1):
                for d in range(i2 - i1): times[i1 + d] = (ww[j1 + d][1] + off, ww[j1 + d][2] + off)
            elif tag == "replace" and j2 > j1:   # spread the span over the script words by length
                s0, s1 = ww[j1][1] + off, ww[j2 - 1][2] + off
                lens = [len(norm(w)) + 1 for w in sw[i1:i2]]; tot = sum(lens); acc = s0
                for d, ln in enumerate(lens):
                    e = acc + (s1 - s0) * ln / tot; times[i1 + d] = (acc, e); acc = e
        # fill gaps by interpolation
        for i in range(len(sw)):
            if times[i] is None:
                prev = next((times[j][1] for j in range(i - 1, -1, -1) if times[j]), L["start"])
                nxt = next((times[j][0] for j in range(i + 1, len(sw)) if times[j]), L["end"])
                run = [j for j in range(i, len(sw)) if times[j] is None]
                run = run[:next((n for n, j in enumerate(run) if j != i + n), len(run))]
                step = (nxt - prev) / len(run)
                for n, j in enumerate(run): times[j] = (prev + n * step, prev + (n + 1) * step)
        words = [{"w": w, "s": round(t[0], 3), "e": round(t[1], 3)} for w, t in zip(sw, times)]
        print(L["id"], "|", r["text"].strip())
        out.append({**L, "asr": r["text"].strip(), "words": words})
    json.dump({"sig": [l["take"] + str(l["start"]) for l in VO["lines"]], "lines": out}, open(cache, "w"), indent=1, ensure_ascii=False)
    return out


def main():
    lines = {l["id"]: l for l in align()}
    total = VO["duration"] + TAIL
    # scene windows
    scenes = []
    for i, (sid, ids) in enumerate(SCENES):
        st = 0.0 if i == 0 else round(lines[ids[0]]["start"] - LEAD, 3)
        scenes.append([sid, st, ids])
    for i, s in enumerate(scenes):
        s.append(round((scenes[i + 1][1] if i + 1 < len(scenes) else total) - s[1], 3))
    cues = {}
    for sid, st, ids, dur in scenes:
        k = {}
        for lid in ids:
            for w in lines[lid]["words"]:
                n = norm(w["w"])
                if n and n not in k: k[n] = round(w["s"] - st, 3)
        cues[sid] = {"start": st, "dur": dur, "k": k}
    with open(f"{PROJ}/assets/cues.js", "w") as f:
        f.write("// generated by build.py: word cues per scene, seconds from scene start\nwindow.CUES = " + json.dumps(cues, indent=1) + ";\n")

    # ---------------- captions
    groups = []
    for lid in [l for _, ids in SCENES for l in ids]:
        ws = lines[lid]["words"]; cur = []
        for i, w in enumerate(ws):
            cur.append(w)
            end_punct = w["w"][-1] in ",.?!"
            nxt_gap = ws[i + 1]["s"] - w["e"] if i + 1 < len(ws) else 9
            if len(cur) >= 3 or end_punct or nxt_gap > 0.18 or i == len(ws) - 1:
                groups.append(cur); cur = []
    cap_html, cap_js = [], []
    for gi, g in enumerate(groups):
        s = g[0]["s"] - 0.06
        e = groups[gi + 1][0]["s"] - 0.06 if gi + 1 < len(groups) and groups[gi + 1][0]["s"] - g[-1]["e"] < 0.6 else g[-1]["e"] + 0.25
        spans = "".join(f'<span class="cw" id="cw{gi}_{j}">{html.escape(re.sub(r"[,.]$", "", w["w"]).upper())}</span> ' for j, w in enumerate(g))
        cap_html.append(f'      <div class="cg" id="cg{gi}"><div class="cb">{spans.strip()}</div></div>')
        cap_js.append(f'      G({gi}, {s:.3f}, {e:.3f}, [{", ".join(f"{w["s"]:.3f}" for w in g)}]);')
    open(f"{PROJ}/compositions/captions.html", "w").write(CAPTIONS.replace("%%GROUPS%%", "\n".join(cap_html)).replace("%%JS%%", "\n".join(cap_js)))

    # ---------------- audio clips
    sfx = make_sfx(cues, lines)
    duck = duck_points(lines, total)
    hosts = []
    for sid, st, ids, dur in scenes:
        hosts.append(f'      <div id="{sid}" data-composition-id="{sid}" data-composition-src="compositions/{sid}.html" data-start="{st}" data-duration="{dur}" data-track-index="1" data-track-kind="graphics" data-width="1080" data-height="1920"></div>')
    import soundfile as sf, subprocess
    def dur(n):
        try: return sf.info(f"{PROJ}/assets/sfx/{n}").duration
        except Exception: return float(subprocess.check_output(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", f"{PROJ}/assets/sfx/{n}"]))
    sfx_html, lanes = [], []
    for i, (name, t, vol) in enumerate(sorted(sfx, key=lambda x: x[1])):
        d = min(dur(name), total - t - 0.01)
        lane = next((j for j, e in enumerate(lanes) if e <= t), None)
        if lane is None: lanes.append(0); lane = len(lanes) - 1
        lanes[lane] = t + d
        sfx_html.append(f'      <audio id="sfx{i}-{name.split(".")[0]}" class="clip" src="assets/sfx/{name}" data-start="{t:.3f}" data-duration="{d:.3f}" data-volume="{vol}" data-track-index="{5 + lane}" data-audio-group="sfx"></audio>')
    autom = json.dumps({"version": 1, "lanes": [{"target": "volume", "points": duck}]}).replace('"', "&quot;")
    idx = INDEX.replace("%%DUR%%", f"{total:.3f}").replace("%%HOSTS%%", "\n".join(hosts)).replace("%%SFX%%", "\n".join(sfx_html)) \
        .replace("%%AUTOM%%", autom).replace("%%VODUR%%", f"{VO['duration']:.3f}").replace("%%BASE%%", open(f"{HERE}/base_inline.css").read())
    open(f"{PROJ}/index.html", "w").write(idx)
    json.dump({"scenes": scenes, "total": total}, open(f"{HERE}/scenes.json", "w"), indent=1)
    for s in scenes: print(s[0], s[1], s[3], s[2])
    print("total", total, "captions", len(groups), "sfx", len(sfx))


def duck_points(lines, total):
    """music volume lane: 1.0 in gaps, 0.32 under speech, with 120 ms ramps"""
    spans = []
    for l in lines.values():
        s, e = l["start"] - 0.12, l["end"] + 0.1
        if spans and s - spans[-1][1] < 0.45: spans[-1][1] = e
        else: spans.append([s, e])
    pts = [{"t": 0, "v": 1.0}]
    for s, e in spans:
        pts += [{"t": round(max(0, s), 3), "v": 1.0}, {"t": round(s + 0.12, 3), "v": 0.45},
                {"t": round(e, 3), "v": 0.45}, {"t": round(e + 0.25, 3), "v": 1.0}]
    pts.append({"t": round(total, 3), "v": 1.0})
    return pts


